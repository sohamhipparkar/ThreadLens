// export.js — Markdown / CSV / JSON exports of an analysis.

const badge = (v) => ({ verified: '✅', review: '⚠️', unsupported: '❌' }[v?.status] || '');

export function toMarkdown(a) {
  const r = a.result;
  const L = [];
  L.push(`# ${a.subject}`, '');
  L.push(`**TL;DR:** ${r.tldr}`, '');
  L.push(`*Faithfulness: ${a.verification.score}% · ${a.stats.messageCount} emails · ${a.stats.mode}*`, '');
  L.push('## Summary');
  r.summary.forEach((s) => L.push(`- ${s.point} _(${s.sources.join(', ')})_ ${badge(s.verification)}`));
  if (r.decisions.length) { L.push('', '## Decisions'); r.decisions.forEach((d) => L.push(`- ${d.decision} _(${d.sources.join(', ')})_ ${badge(d.verification)}`)); }
  L.push('', '## Action items', '', '| # | Task | Owner | Due | Status | Priority | Source | Check |', '|---|---|---|---|---|---|---|---|');
  r.action_items.forEach((x, i) => L.push(`| ${i + 1} | ${x.task.replace(/\|/g, '/')} | ${x.owner} | ${x.due} | ${x.status} | ${x.priority} | ${x.source} | ${badge(x.verification)} |`));
  if (r.open_questions.length) { L.push('', '## Open questions'); r.open_questions.forEach((q) => L.push(`- ${q.question} _(${q.sources.join(', ')})_`)); }
  L.push('', '---', '_Generated by ThreadLens — AI output, verify before acting._');
  return L.join('\n');
}

export function toCSV(a) {
  const esc = (v) => `"${String(v ?? '').replace(/"/g, '""')}"`;
  const head = ['Task', 'Owner', 'Due', 'Status', 'Priority', 'Source', 'Evidence', 'Verification'];
  const rows = a.result.action_items.map((x) => [x.task, x.owner, x.due, x.status, x.priority, x.source, x.evidence, x.verification?.status]);
  return [head, ...rows].map((r) => r.map(esc).join(',')).join('\n');
}

export function toJSON(a) {
  return JSON.stringify({ subject: a.subject, participants: a.participants, stats: a.stats, verification: a.verification, ...a.result }, null, 2);
}
