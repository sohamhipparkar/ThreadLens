"""setup.py — same as setup.js for people who prefer Python: reads .env, writes extension/config.js.
Usage: python setup.py
"""
import json, re, shutil
from pathlib import Path

root = Path(__file__).parent
env_path = root / '.env'
if not env_path.exists():
    shutil.copy(root / '.env.example', env_path)
    print('Created .env from .env.example — add your GEMINI_API_KEY and run again.')
env = {}
for line in env_path.read_text(encoding='utf-8').splitlines():
    m = re.match(r'^\s*([A-Z0-9_]+)\s*=\s*(.*?)\s*$', line)
    if m:
        env[m.group(1)] = m.group(2).strip('"\'')
(root / 'extension' / 'config.js').write_text(
    '// AUTO-GENERATED by setup.py from .env — do not edit by hand, do not commit with a real key.\n'
    f'export default {json.dumps(env, indent=2)};\n', encoding='utf-8')
print(f'Wrote extension/config.js ({len(env)} settings).')
print('Gemini API key: set ✓' if env.get('GEMINI_API_KEY') else 'Gemini API key: MISSING — add it to .env (or paste it in the extension Settings).')
print('Now reload the extension at chrome://extensions.')
