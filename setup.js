// setup.js — reads .env and writes extension/config.js (no dependencies).
// Usage: node setup.js
const fs = require('fs');
const path = require('path');

const envPath = path.join(__dirname, '.env');
if (!fs.existsSync(envPath)) {
  fs.copyFileSync(path.join(__dirname, '.env.example'), envPath);
  console.log('Created .env from .env.example — add your GEMINI_API_KEY and run again.');
}
const env = {};
for (const line of fs.readFileSync(envPath, 'utf8').split(/\r?\n/)) {
  const m = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*)\s*$/);
  if (m) env[m[1]] = m[2].replace(/^["']|["']$/g, '');
}
const out = `// AUTO-GENERATED by setup.js from .env — do not edit by hand, do not commit with a real key.\nexport default ${JSON.stringify(env, null, 2)};\n`;
fs.writeFileSync(path.join(__dirname, 'extension', 'config.js'), out);
console.log(`Wrote extension/config.js (${Object.keys(env).length} settings).`);
console.log(env.GEMINI_API_KEY ? 'Gemini API key: set ✓' : 'Gemini API key: MISSING — add it to .env (or paste it in the extension Settings).');
console.log('Now reload the extension at chrome://extensions.');
